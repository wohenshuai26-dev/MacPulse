@main
struct MacPulseControlsBundle: WidgetBundle {
    var body: some Widget {
        CPUTempControl()
        CPUUsageControl()
        MemoryControl()
        FanControl()
    }
}

/// Reads the latest sample the MacPulse app wrote into the shared App Group container.
struct SnapshotProvider: ControlValueProvider {
    var previewValue: Snapshot { .preview }

    private static let log = Logger(subsystem: Bundle.main.bundleIdentifier ?? "MacPulse", category: "controls")

    func currentValue() async throws -> Snapshot {
        let s = SnapshotStore.read() ?? .unavailable
        Self.log.debug("currentValue temp=\(s.tempText, privacy: .public) cpu=\(s.usageText, privacy: .public) age=\(Int(Date().timeIntervalSince(s.date)), privacy: .public)s")
        return s
    }
}

enum ControlKind {
    /// e.g. "com.yourname.MacPulse.cpuTemp", from MP_BUNDLE_PREFIX via Info.plist.
    private static let base = (Bundle.main.object(forInfoDictionaryKey: "MPBundlePrefix") as? String ?? "MacPulse") + ".MacPulse."
    static let cpuTemp = base + "cpuTemp"
    static let cpuUsage = base + "cpuUsage"
    static let memory = base + "memory"
    static let fan = base + "fan"
}

/// Custom number symbols (generated by tools/make_symbols.swift) let the 1×1 control,
/// which only shows its icon, display the value itself. Falls back to an SF Symbol when stale.
private func icon(_ custom: String?, fallback: String) -> Image {
    custom.map { Image($0) } ?? Image(systemName: fallback)
}

extension Snapshot {
    var tempSymbol: String? {
        guard !isStale, let t = cpuTemp else { return nil }
        return "mp.temp.\(min(max(Int(t.rounded()), 0), 120))"
    }
    var usageSymbol: String? {
        isStale ? nil : "mp.pct.\(min(max(Int((cpuUsage * 100).rounded()), 0), 100))"
    }
    var memSymbol: String? {
        guard !isStale, memTotal > 0 else { return nil }
        let gb = Int(Self.gb(memUsed).rounded())
        return gb <= 192 ? "mp.gb.\(gb)" : nil
    }
    var fanSymbol: String? {
        guard !isStale, let rpm = fanRPM else { return nil }
        return "mp.fan.\(min(max(Int((rpm / 100).rounded()), 0), 99))"
    }
}

private func tint(for level: Snapshot.Level) -> Color {
    switch level {
    case .normal: return .green
    case .warm: return .orange
    case .hot: return .red
    }
}

struct CPUTempControl: ControlWidget {
    var body: some ControlWidgetConfiguration {
        StaticControlConfiguration(kind: ControlKind.cpuTemp, provider: SnapshotProvider()) { s in
            ControlWidgetButton(action: OpenDashboardIntent()) {
                Label {
                    Text(s.tempText)
                    Text("CPU 溫度")
                } icon: {
                    icon(s.tempSymbol, fallback: "thermometer.medium")
                }
            }
            .tint(tint(for: s.tempLevel))
        }
        .displayName("CPU 溫度")
        .description("顯示 CPU 晶片平均溫度")
    }
}

